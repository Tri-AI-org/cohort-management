/**
 * auth-callback.mjs
 *
 * GET /.netlify/functions/auth-callback?t=<token>
 *
 * Exchanges a magic-link token for a session cookie, then 302s
 * the user to /[number]/me (the destination they're presumably
 * here to see).
 *
 * Why GET, not POST: the user follows a link from their email.
 * The browser issues GET. POSTing a magic-link consume is the
 * "correct" idempotent thing in theory, but in practice it
 * requires interstitial JS which breaks for users on email apps
 * with embedded webviews.
 *
 * Single-use enforcement: we set consumed_at on first use. A
 * second request with the same token finds consumed_at != NULL
 * and refuses. This means re-clicking the email link after
 * successful login fails — by design.
 */

import { query, tx } from './_lib/db.mjs';
import {
  hashMagicToken, newSessionToken, sessionCookieHeader, TOKEN_LIFETIMES,
} from './_lib/auth.mjs';
import {
  json, CORS, requireEnv, getClientIp, audit,
} from './_lib/http.mjs';

function htmlError(title, message) {
  // A friendly error page for users who get here with a bad/expired
  // token. We render HTML directly rather than redirecting because
  // a redirect loses the context of *why* they ended up somewhere.
  const safe = s => String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  return {
    statusCode: 400,
    headers: { 'Content-Type': 'text/html; charset=utf-8', ...CORS },
    body: `<!doctype html><html><head><meta charset="utf-8">
<title>${safe(title)} — TRI AI Portal</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
  body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif;
         background: #fafafa; color: #141414; padding: 48px 24px;
         max-width: 480px; margin: 0 auto; line-height: 1.6; }
  h1 { font-size: 22px; margin-bottom: 12px; }
  a  { color: #FE6612; }
</style></head>
<body>
  <h1>${safe(title)}</h1>
  <p>${safe(message)}</p>
  <p><a href="https://cohort.tri-ai.org/">← Back to the portal</a></p>
</body></html>`,
  };
}

export const handler = async (event) => {
  if (event.httpMethod !== 'GET') return json(405, { error: 'Method not allowed' });

  const envCheck = requireEnv(['DATABASE_URL', 'SESSION_SECRET', 'PORTAL_BASE_URL']);
  if (envCheck) return envCheck;

  const token = event.queryStringParameters?.t;
  if (!token) return htmlError('Missing token', 'The sign-in link is incomplete. Please request a new one.');

  // Optional ?next=/some/path — where to send the user after sign-in.
  // Used by reminder emails (next=/10/check-in) and onboarding emails
  // (default destinations apply if absent). We accept ONLY same-site
  // paths starting with '/' — never absolute URLs — to prevent
  // open-redirect attacks.
  let nextPath = event.queryStringParameters?.next;
  if (nextPath && (!nextPath.startsWith('/') || nextPath.startsWith('//'))) {
    nextPath = null;
  }

  const tokenHash = hashMagicToken(token);
  const ip = getClientIp(event);
  const ua = event.headers['user-agent'] || '';

  // Look up + consume in a transaction so two concurrent clicks
  // can't both succeed. Also fetches the person + enrolment so
  // we can build a useful session payload.
  let result;
  try {
    result = await tx(async (c) => {
      // Lock-and-load: SELECT FOR UPDATE so a second click waits
      // here, sees the row already consumed, and bails cleanly.
      const r = await c.query(
        `SELECT id, email, cohort_id, expires_at, consumed_at
           FROM magic_link_tokens
          WHERE token_hash = $1
          FOR UPDATE`,
        [tokenHash]
      );
      if (r.rows.length === 0) return { error: 'unknown' };
      const row = r.rows[0];
      if (row.consumed_at) return { error: 'consumed' };
      if (new Date(row.expires_at) < new Date()) return { error: 'expired' };

      await c.query(
        `UPDATE magic_link_tokens
            SET consumed_at = now(), consume_ip = $2, consume_ua = $3
          WHERE id = $1`,
        [row.id, ip, ua]
      );

      // Resolve the person and the role on this cohort so we put
      // it in the session.
      const pr = await c.query(
        `SELECT p.id AS person_id, e.role
           FROM people p
           LEFT JOIN enrolments e
             ON e.person_id = p.id AND e.cohort_id = $2 AND e.status = 'active'
          WHERE p.email = $1`,
        [row.email, row.cohort_id]
      );

      return {
        email:     row.email,
        cohortId:  row.cohort_id,
        personId:  pr.rows[0]?.person_id,
        role:      pr.rows[0]?.role || 'student',
      };
    });
  } catch (err) {
    console.error('auth-callback tx failed:', err);
    return htmlError('Something went wrong', 'We could not sign you in right now. Please try again in a minute.');
  }

  if (result.error === 'unknown') {
    return htmlError('Sign-in link not found',
      'This link was not recognised. It may have been mistyped — or generated by a different system. Request a fresh link from the sign-in page.');
  }
  if (result.error === 'consumed') {
    return htmlError('Already used',
      'This sign-in link has already been used. For security, each link works only once. Request a new one from the sign-in page.');
  }
  if (result.error === 'expired') {
    return htmlError('Link expired',
      'For security, sign-in links expire after 30 minutes. Request a fresh one from the sign-in page.');
  }

  // Look up the cohort number so we can build the destination URL.
  const cohortRow = await query(
    `SELECT number FROM cohorts WHERE id = $1`,
    [result.cohortId]
  );
  const cohortNumber = cohortRow[0]?.number;

  // Build the session. The session `kind` matches the user's role on
  // this cohort — so a facilitator gets a 'facilitator' session, not
  // a 'student' one (which would later bounce them off /facilitator
  // pages). Both roles get the long-lived 30-day cookie because
  // (a) magic-link emails are expensive at our volume and (b) the
  // tokens are short-lived anyway.
  const sessionKind = result.role === 'facilitator' ? 'facilitator' : 'student';
  const token2 = newSessionToken({
    kind:     sessionKind,
    email:    result.email,
    personId: result.personId,
    cohortId: result.cohortId,
    role:     result.role,
  }, TOKEN_LIFETIMES.student);

  await audit({
    action: 'auth_callback_success',
    actorEmail: result.email,
    actorKind: sessionKind,
    cohortId: result.cohortId,
    ip, userAgent: ua,
  });

  // 302 to wherever. Priority order:
  //   1. ?next=/path query param (used by reminder/onboarding emails)
  //   2. role-default: /me for students, /facilitator for facilitators
  const portalBase = process.env.PORTAL_BASE_URL.replace(/\/$/, '');
  let dest;
  if (nextPath) {
    dest = portalBase + nextPath;
  } else if (result.role === 'facilitator') {
    dest = `${portalBase}/${cohortNumber}/facilitator`;
  } else {
    dest = `${portalBase}/${cohortNumber}/me`;
  }

  return {
    statusCode: 302,
    headers: {
      Location: dest,
      'Set-Cookie': sessionCookieHeader(token2, TOKEN_LIFETIMES.student),
      ...CORS,
    },
    body: '',
  };
};
